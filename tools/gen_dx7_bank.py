"""Generate the compiled DX7 factory bank (bank.h) from assets/dx7/factory.packed.

factory.packed is written by tools/dx7_candidates.py (original project voices). Voice names come from the
patches themselves (bytes 118..127).
"""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
 data=(ROOT/'assets/dx7/factory.packed').read_bytes()
 if not data or len(data)%128:raise ValueError('bank length must be a multiple of 128')
 n=len(data)//128
 if n>10:raise ValueError('preset ID space holds at most 10 factory voices (64..73)')
 out=['/* Generated by tools/gen_dx7_bank.py from assets/dx7/factory.packed; voices are original project data (assets/dx7/README.md). */\n#ifndef MIKU_DX7_BANK_H\n#define MIKU_DX7_BANK_H\n#include <stdint.h>\n#define DX7_BANK_N %du\nstatic const uint8_t dx7_bank[DX7_BANK_N][128]={\n'%n]
 names=[]
 for i in range(n):
  patch=data[i*128:(i+1)*128]
  if any(x>127 for x in patch):raise ValueError('patch byte out of range')
  names.append(patch[118:128].decode('ascii').strip(' \x00').upper())
  out.append('{'+','.join(map(str,patch))+'},\n')
 out.append('};\nstatic const char *const dx7_names[DX7_BANK_N]={'+','.join(json.dumps(x) for x in names)+'};\n#endif\n')
 return ''.join(out)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();dst=ROOT/'firmware/audio/dx7/bank.h';out=generate()
 if a.check:
  if dst.read_text()!=out:raise SystemExit('DX7 bank header is stale')
 else:dst.write_text(out)
