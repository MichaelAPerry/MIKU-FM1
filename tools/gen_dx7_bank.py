"""Generate the compiled DX7 shortlist from the pinned original packed voices."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
 data=(ROOT/'assets/dx7/factory.packed').read_bytes();plan=json.loads((ROOT/'config/dx7/review_bank.json').read_text())
 if len(data)!=128*len(plan['voices']):raise ValueError('bank length mismatch')
 out=['/* Generated by tools/gen_dx7_bank.py; patch provenance: assets/dx7/README.md. */\n#ifndef MIKU_DX7_BANK_H\n#define MIKU_DX7_BANK_H\n#include <stdint.h>\n#define DX7_BANK_N 8u\nstatic const uint8_t dx7_bank[DX7_BANK_N][128]={\n']
 for i in range(8):
  patch=data[i*128:(i+1)*128]
  if patch[118:128].decode('ascii').strip(' \x00')!=plan['voices'][i]['name']:raise ValueError('patch identity mismatch')
  out.append('{'+','.join(map(str,patch))+'},\n')
 out.append('};\nstatic const char *const dx7_names[DX7_BANK_N]={'+','.join(json.dumps(v['name'].upper()) for v in plan['voices'])+'};\n#endif\n')
 return ''.join(out)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();dst=ROOT/'firmware/audio/dx7/bank.h';out=generate()
 if a.check:
  if dst.read_text()!=out:raise SystemExit('DX7 bank header is stale')
 else:dst.write_text(out)
