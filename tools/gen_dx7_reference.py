"""Regenerate independent MSFA vectors from an unmodified upstream jni checkout."""
import argparse,struct,subprocess,tempfile,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('upstream',type=Path);p.add_argument('--cxx',default='c++');p.add_argument('--check',action='store_true');a=p.parse_args()
 stems=['dx7note','env','pitchenv','fm_core','fm_op_kernel','exp2','sin','freqlut']
 with tempfile.TemporaryDirectory() as tmp:
  t=Path(tmp)
  for name in ['synth.h','aligned_buf.h']+[n+ext for n in stems for ext in ['.h','.cc']]:shutil.copyfile(a.upstream/name,t/name)
  (t/'controllers.h').write_text('const int kControllerPitch=0; struct Controllers {int values_[1];};\n')
  (t/'patch.h').write_text('/* No patch transport in the reference adapter. */\n')
  shutil.copyfile(ROOT/'tools/dx7_reference.cc',t/'reference.cc')
  subprocess.run([a.cxx,'-std=c++11','-O2','-fwrapv','-include','stddef.h','-I'+str(t),str(t/'reference.cc')]+[str(t/(n+'.cc')) for n in stems]+['-lm','-o',str(t/'reference')],check=True)
  data=(ROOT/'assets/dx7/factory.packed').read_bytes();rows=[]
  for i in range(len(data)//128):
   (t/'voice.bin').write_bytes(data[i*128:(i+1)*128]);subprocess.run([str(t/'reference'),str(t/'voice.bin'),str(t/'audio.raw')],check=True)
   raw=struct.unpack('<4096i',(t/'audio.raw').read_bytes());rows.append('{'+','.join(str(raw[n*128]) for n in range(32))+'},')
  s='/* SPDX-License-Identifier: Apache-2.0\n * Independent raw Q24 reference vectors generated by original Google MSFA\n * for assets/dx7/factory.packed (the original MIKU factory voices)\n * f67d41d313b7dc85f6fb99e79e515cc9d208cfff. See README.md for conditions. */\nstatic const int32_t dx_reference[%d][32]={\n'%len(rows)+'\n'.join(rows)+'\n};\n'
  out=ROOT/'firmware/audio/dx7/reference_vectors.h'
  if a.check:
   if out.read_text()!=s:raise SystemExit('MSFA reference vectors differ')
  else:out.write_text(s)
if __name__=='__main__':main()
