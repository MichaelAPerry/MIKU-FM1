"""Generate immutable MSFA fixed-point lookup tables; no libm is used on device."""
import argparse
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def emit():
    values={
      'dx_sine': [round(math.sin(2*math.pi*i/1024)*(1<<24)) for i in range(1025)],
      'dx_exponential': [math.floor((2**(i/1024))*(1<<30)+.5) for i in range(1025)],
      'dx_frequency': [math.floor((2**(i/1024))*(1<<44)/44100+.5) for i in range(1025)],
      'dx_fine': [math.floor(24204406.323123*math.log(1+.01*i)+.5) for i in range(100)],
    }
    # The final exp2 endpoint is represented unsigned (2^31); the interpolator
    # uses signed 64-bit differences before reducing to the Q24 gain domain.
    lines=['/* Generated by tools/gen_dx7_tables.py. SPDX-License-Identifier: Apache-2.0 */','#ifndef MIKU_DX7_TABLES_H','#define MIKU_DX7_TABLES_H']
    for name,vs in values.items():
        kind='uint32_t' if name=='dx_exponential' else 'int32_t'
        lines.append(f'static const {kind} {name}[{len(vs)}]={{')
        lines.extend('    '+','.join(str(v) for v in vs[i:i+12])+',' for i in range(0,len(vs),12))
        lines.append('};')
    lines.append('#endif\n');return '\n'.join(lines)
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    p=ROOT/'firmware/audio/dx7/dx7_tables.h';s=emit()
    if args.check:
        if not p.exists() or p.read_text()!=s:raise SystemExit('DX7 generated tables differ')
    else:p.write_text(s)
if __name__=='__main__':main()
