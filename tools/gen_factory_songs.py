"""Compile editable public-domain song transcriptions to sparse native tables."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
    mora=re.findall(r'M\("([^"]*)",', (ROOT/'firmware/song/mora.c').read_text())
    names={n:i for i,n in enumerate(mora)}
    songs=json.loads((ROOT/'assets/songs/factory/songs.json').read_text())['songs']
    out=['/* Generated by tools/gen_factory_songs.py. Sources: assets/songs/factory/README.md. */\n']
    stats=[]
    for i,s in enumerate(songs):
        at=0;events=[];vowel=1
        for e in s['events']:
            note=e['note'];ticks=e['ticks'];tokens=e['lyric'].split('+')
            assert 1<=ticks<=64 and len(tokens)<=ticks
            if note=='R':pitch=0
            else:
                m=re.fullmatch(r'([A-G])([b#]?)([0-8])',note);assert m,note
                pitch=(int(m[3])+1)*12+{'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}[m[1]]+{'':0,'#':1,'b':-1}[m[2]]
            for j,token in enumerate(tokens):
                length=ticks//len(tokens)+(j<ticks%len(tokens))
                if token=='/':assert not pitch;mid=0;flags=128
                elif token=='_':mid=vowel;flags=16|32
                else:mid=names[token];vowel=mid;flags=16
                remaining=length;continuation=False
                while remaining:
                    n=min(remaining,16-at%16)
                    events.append((at,pitch,n,mid,flags|12|(32 if continuation else 0)))
                    at+=n;remaining-=n;continuation=True
        assert at==s['verse_ticks'] and at<=16*16
        rows=(at+15)//16;assert rows==len(s['roots']),(s['id'],rows,len(s['roots']))
        out.append(f'static const SfNote SF_NOTES_{i}[]={{\n')
        out.extend('    {'+','.join(map(str,e))+'},\n' for e in events)
        out.append('};\nstatic const uint8_t SF_ROOTS_'+str(i)+'[]={'+','.join(map(str,s['roots']))+'};\n')
        stats.append({'id':s['id'],'ticks':at,'rows':rows+1,'events':len(events),'duration_seconds':at*15/s['bpm']})
    out.append('static const SfSong SF_SONGS[SF_COUNT]={\n')
    for i,s in enumerate(songs):
        out.append('    {"'+s['name']+'","'+s['title'].upper()+'",'+str(s['bpm'])+','+str((s['verse_ticks']+15)//16)+','+str(s['source_meter'])+',SF_NOTES_'+str(i)+',sizeof SF_NOTES_'+str(i)+'/sizeof(SfNote),SF_ROOTS_'+str(i)+'},\n')
    out.append('};\n');return ''.join(out),stats
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args();s,stats=generate();p=ROOT/'firmware/song/factory_tables.h'
    if a.check:assert p.read_text()==s,'factory song tables stale'
    else:p.write_text(s)
    print(json.dumps(stats,indent=2))
