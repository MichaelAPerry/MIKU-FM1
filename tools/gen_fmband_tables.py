# Offline constants for firmware/audio/fmband (integer-only on the device).
# Usage: tools/gen_fmband_tables.py [outdir]   (default firmware/audio/fmband) -> fmband_tables.h/.c
import math, os, sys

FS = 44100
BLK = 16                      # frames per control block
BR = FS / BLK                 # control blocks per second
NT = 64                       # time-index table size: T = 2 ms .. 8 s, geometric
T0, T1 = 2.0, 8000.0
SILENCE = 4096 / 2**24        # envelopes snap to 0 at -72 dB

def tms(i): return T0 * (T1 / T0) ** (i / (NT - 1))

def rows(v, per=16, fmt="%d"):
    s = []
    for i in range(0, len(v), per):
        s.append(" " + ",".join(fmt % x for x in v[i:i + per]) + ",")
    return "\n".join(s)

def build():
    sin = [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1024)]
    # soft square: odd harmonics to 11 with Lanczos sigma, normalised to peak 32767
    H = 11
    sq = []
    for i in range(1024):
        x = 0.0
        for n in range(1, H + 1, 2):
            sg = math.sin(math.pi * n / (H + 1)) / (math.pi * n / (H + 1))
            x += sg * math.sin(2 * math.pi * n * i / 1024) / n
        sq.append(x)
    pk = max(abs(x) for x in sq)
    sq = [int(round(32767 * x / pk)) for x in sq]
    inc = [int(round(440.0 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS)) for n in range(129)]
    kdec, katk, tm = [], [], []
    for i in range(NT):
        T = tms(i); nb = T * BR / 1000.0
        kdec.append(min(65535, int(round(65536 * (1 - math.exp(math.log(SILENCE) / nb))))))
        katk.append(max(1, int(round(2 ** 24 / nb))))
        tm.append(int(round(T)))
    pan = [int(round(32767 * math.cos(math.pi / 2 * i / 64))) for i in range(65)]
    return sin, sq, inc, kdec, katk, tm, pan

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "firmware", "audio", "fmband")
    sin, sq, inc, kdec, katk, tm, pan = build()
    hdr = """/* SPDX-License-Identifier: GPL-3.0-only */
/* GENERATED by tools/gen_fmband_tables.py - do not edit. */
#ifndef FMBAND_TABLES_H
#define FMBAND_TABLES_H
#include <stdint.h>
extern const int16_t fmb_sin[1024];   /* sine, index = phase >> 22 */
extern const int16_t fmb_sq[1024];    /* band-limited soft square (odd harmonics to 11) */
extern const uint32_t fmb_inc[129];   /* phase increment per sample, MIDI 0..128, 2^32 = 1 cycle */
extern const uint16_t fmb_kdec[64];   /* per-block decay constant /65536 so Q24 envelope falls 72 dB in fmb_tms[i] */
extern const uint32_t fmb_katk[64];   /* per-block linear attack step (Q24) for a rise in fmb_tms[i] */
extern const uint16_t fmb_tms[64];    /* time of index i in ms (2 ms .. 8 s, geometric) */
extern const uint16_t fmb_pan[65];    /* cos(pi/2 * i/64), Q15 */
#endif
"""
    src = "/* SPDX-License-Identifier: GPL-3.0-only */\n/* GENERATED by tools/gen_fmband_tables.py - do not edit. */\n#include \"firmware/audio/fmband/fmband_tables.h\"\n"
    for name, t, v in (("int16_t", "fmb_sin[1024]", sin), ("int16_t", "fmb_sq[1024]", sq), ("uint32_t", "fmb_inc[129]", inc),
                       ("uint16_t", "fmb_kdec[64]", kdec), ("uint32_t", "fmb_katk[64]", katk), ("uint16_t", "fmb_tms[64]", tm),
                       ("uint16_t", "fmb_pan[65]", pan)):
        src += "const %s %s={\n%s\n};\n" % (name, t, rows(v))
    open(os.path.join(out, "fmband_tables.h"), "w").write(hdr)
    open(os.path.join(out, "fmband_tables.c"), "w").write(src)

if __name__ == "__main__":
    main()
