"""Deterministic lossless row atlas from canonical singer_sprites.h. Stdlib only.
Original assets/header are never overwritten. --check compares generated bytes.
Each unique row chooses raw packed nibbles, nibble RLE, or a one-level delta
against that frame's neutral row. No decoder chain or full-frame scratch needed.
"""
from pathlib import Path
import argparse
import re
ROOT = Path(__file__).resolve().parents[1]


def parse(text, name):
    found = re.search(r'\b' + re.escape(name) + r'\[[^\]]*\](?:\[\d+\])? = \{(.*?)\n\};', text, re.S)
    if not found:
        raise ValueError('missing array ' + name)
    body = re.sub(r'/\*.*?\*/', '', found[1], flags=re.S)
    return [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', body)]


def direct(row):
    packed = bytes((row[i] << 4) | (row[i + 1] if i + 1 < len(row) else 0) for i in range(0, len(row), 2))
    runs = []
    for colour in row:
        if runs and runs[-1] & 15 == colour and runs[-1] >> 4 < 15:
            runs[-1] += 16
        else:
            runs.append(colour)
    # Ties prefer raw: bounded O(1) pixel lookup on detailed rows.
    return bytes([1] + runs) if len(runs) < len(packed) else bytes([0]) + packed


def pack_atlas(frames, width, height, use_delta=True):
    lookup, records, originals, ids = {}, [], [], []
    for fi, flat in enumerate(frames):
        for y in range(height):
            row = tuple(flat[y * width:(y + 1) * width])
            if row not in lookup:
                record = direct(row)
                if use_delta and fi:
                    base = tuple(frames[0][y * width:(y + 1) * width])
                    base_id = lookup[base]
                    # No delta chains: base records must be independently decodable.
                    diff = [x for x in range(width) if row[x] != base[x]]
                    if diff and records[base_id][0] != 2:
                        x, end = diff[0], diff[-1] + 1
                        delta = bytes([2, base_id & 255, base_id >> 8, x, end - x]) + direct(row[x:end])
                        if len(delta) < len(record):
                            record = delta
                lookup[row] = len(records)
                records.append(record)
                originals.append(row)
            ids.append(lookup[row])
    offsets, data = [0], bytearray()
    for record in records:
        data.extend(record)
        offsets.append(len(data))
    if len(data) > 65535 or len(records) > 65535:
        raise ValueError('atlas exceeds 16-bit compact limits')
    return ids, offsets, data, originals


def decode_python(packed, row_id):
    _, offsets, data, _ = packed
    chunk = data[offsets[row_id]:offsets[row_id + 1]]
    mode = chunk[0]
    if mode == 2:
        base = decode_python(packed, chunk[1] | chunk[2] << 8)
        patch = unpack_direct(chunk[5:], chunk[4])
        base[chunk[3]:chunk[3] + chunk[4]] = patch
        return base
    return unpack_direct(chunk, len(packed[3][row_id]))


def unpack_direct(chunk, width):
    if chunk[0] == 0:
        return [v for b in chunk[1:] for v in (b >> 4, b & 15)][:width]
    return [v for b in chunk[1:] for v in [b & 15] * ((b >> 4) + 1)]


def array(name, typ, vals, per=16):
    lines = [f'static const {typ} {name}[{len(vals)}] = {{']
    lines += ['    ' + ', '.join(str(x) for x in vals[i:i + per]) + ',' for i in range(0, len(vals), per)]
    return '\n'.join(lines) + '\n};\n'


def generate(text):
    out = ['''/* GENERATED by tools/sprite_compact.py; do not edit.
 * Source: singer_sprites.h, fan art of Hatsune Miku, Crypton Future Media, INC.
 * Character pixels remain under the Piapro Character License (free/noncommercial),
 * NOT the code GPL. See LICENSING.md. Original art/header remain unchanged.
 */
#ifndef SINGER_COMPACT_H
#define SINGER_COMPACT_H
#include "firmware/ui/sprite_codec.h"
''']
    reports = []
    for kind, width, height, count in [('FACE', 90, 90, 12), ('STAGE', 61, 71, 8)]:
        frames = []
        for fi in range(count):
            a = parse(text, f'singer_{kind.lower()}_{fi}')
            if len(a) != (width * height + 1) // 2 or any(v > 255 for v in a):
                raise ValueError('invalid source frame dimensions or pixel byte')
            frames.append([v for b in a for v in (b >> 4, b & 15)][:width * height])
        packed = pack_atlas(frames, width, height)
        ids, offsets, data, originals = packed
        for i, expected in enumerate(originals):
            if decode_python(packed, i) != list(expected):
                raise ValueError('self-check failed')
        name = 'SC_' + kind
        out += [array(name + '_ROWS', 'uint16_t', ids), array(name + '_OFFSETS', 'uint16_t', offsets), array(name + '_DATA', 'uint8_t', data)]
        out += [f'static const SprAtlas {name}_ATLAS = {{ {width}, {height}, {count}, {len(originals)}, {len(data)}, {name}_ROWS, {name}_OFFSETS, {name}_DATA }};\n']
        out += [array(name + '_PAL', 'uint16_t', parse(text, 'SINGER_' + kind + '_PAL'))]
        direct_pack = pack_atlas(frames, width, height, False)
        total = len(data) + 2 * len(ids) + 2 * len(offsets)
        no_delta = len(direct_pack[2]) + 2 * len(direct_pack[0]) + 2 * len(direct_pack[1])
        reports.append(f'{kind}: original={count*((width*height+1)//2)} compact={total} direct-row={no_delta} unique_rows={len(originals)} delta_rows={sum(data[offsets[i]]==2 for i in range(len(originals)))}')
    out += [array('SC_FACE_DIRTY', 'uint8_t', parse(text, 'SINGER_FACE_DIRTY')), '#endif\n']
    return ''.join(out), reports


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--source', type=Path, default=ROOT / 'firmware/ui/singer_sprites.h')
    ap.add_argument('--output', type=Path, default=ROOT / 'firmware/ui/singer_compact.h')
    args = ap.parse_args()
    text, reports = generate(args.source.read_text())
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit('compact sprite header is stale')
    else:
        args.output.write_text(text)
    print('\n'.join(reports))


if __name__ == '__main__':
    main()
