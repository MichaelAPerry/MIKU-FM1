"""Pack four four-frame stage effects into a shared 32px indexed atlas."""
import argparse
from pathlib import Path
from PIL import Image
import sprite_compact as codec
ROOT = Path(__file__).resolve().parents[1]

def generate():
    im = Image.open(ROOT / 'assets/stage/effects.png').convert('RGBA')
    frames = []
    palette = [0, 0xffff, 0xffa0, 0xf81f, 0x07ff, 0x07e0, 0xf800, 0x8410]
    rgb = [((p >> 11)*255//31, ((p >> 5)&63)*255//63, (p&31)*255//31) for p in palette]
    preview = Image.new('RGBA', (128,128))
    for y in range(4):
        for x in range(4):
            tile = im.crop((x*im.width//4,y*im.height//4,(x+1)*im.width//4,(y+1)*im.height//4))
            tile.thumbnail((32,32), Image.Resampling.NEAREST)
            cell = Image.new('RGBA',(32,32)); cell.alpha_composite(tile,((32-tile.width)//2,(32-tile.height)//2))
            values=[]
            for r,g,b,a in cell.getdata():
                values.append(0 if a<160 else min(range(1,len(rgb)),key=lambda i:(r-rgb[i][0])**2+(g-rgb[i][1])**2+(b-rgb[i][2])**2))
            frames.append(values)
            cell.putdata([(*rgb[i],255 if i else 0) for i in values]); preview.alpha_composite(cell,(x*32,y*32))
    ids, offsets, data, rows = codec.pack_atlas(frames,32,32)
    for i,row in enumerate(rows):
        assert codec.decode_python((ids,offsets,data,rows),i)==list(row)
    out='/* Generated by tools/stagefx_pack.py; art: see assets/stage/README.md. */\n#ifndef MIKU_STAGEFX_SPRITES_H\n#define MIKU_STAGEFX_SPRITES_H\n#include "sprite_codec.h"\n'
    for suffix,typ,values in [('ROWS','uint16_t',ids),('OFFSETS','uint16_t',offsets),('DATA','uint8_t',data),('PAL','uint16_t',palette)]:
        out+=codec.array('FX_'+suffix,typ,values)
    out+=f'static const SprAtlas FX_ATLAS={{32,32,16,{len(rows)},{len(data)},FX_ROWS,FX_OFFSETS,FX_DATA}};\n#endif\n'
    return out,preview,len(data)+2*len(ids)+2*len(offsets)+2*len(palette)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');ap.add_argument('--preview',type=Path);args=ap.parse_args()
    out,preview,size=generate();path=ROOT/'firmware/ui/stagefx_sprites.h'
    if args.check:
        assert path.read_text()==out,'stage effect header is stale'
    else:path.write_text(out)
    if args.preview:
        args.preview.parent.mkdir(parents=True,exist_ok=True);preview.save(args.preview)
    print(f'stage effects: 16 frames, {size} atlas bytes')
